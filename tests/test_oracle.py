"""Cross-check ``expand`` against real POSIX shells.

``tests/data/oracle_corpus.json`` holds templates generated by
``scripts/build_corpus.py`` and the outputs dash and bash --posix printed for
them in WSL. The live test regenerates a fresh seeded batch and asks dash
directly; it is skipped when WSL with dash is not available.
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

import pytest

from shtemplate import ExpansionError, expand

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import build_corpus  # noqa: E402
import oracle  # noqa: E402

CORPUS = json.loads((ROOT / "tests" / "data" / "oracle_corpus.json").read_text("utf-8"))

# Documented deviations from dash, each with the reason.
DEVIATIONS = {
    # Special parameters do not exist in a mapping, so $- stays literal text.
    "$-": ["ok", "$-"],
    # POSIX: quoted pattern characters match themselves. bash agrees; dash
    # treats the bracket expression from "$R" as active.
    '${R#"$R"}': ["ok", ""],
}


def ours(template: str, env: dict[str, str], strict: bool) -> list[str]:
    try:
        return ["ok", expand(template, env, strict=strict)]
    except ExpansionError:
        return ["error", ""]


def test_corpus_is_large_and_mostly_agreed_by_both_shells() -> None:
    cases = CORPUS["cases"]
    assert len(cases) >= 1600
    agreed = sum(1 for case in cases if case["dash"] == case["bash"])
    assert agreed / len(cases) > 0.99


def test_every_corpus_case_matches_dash_or_a_documented_deviation() -> None:
    env = CORPUS["env"]
    mismatches = []
    for case in CORPUS["cases"]:
        got = ours(case["template"], env, case["strict"])
        expected = DEVIATIONS.get(case["template"], case["dash"])
        if got != expected:
            mismatches.append((case["template"], case["strict"], got, case["dash"]))
    assert mismatches == []


def test_documented_deviations_match_bash_or_are_literal() -> None:
    env = CORPUS["env"]
    by_template = {case["template"]: case for case in CORPUS["cases"]}
    assert ours('${R#"$R"}', env, False) == by_template['${R#"$R"}']["bash"]
    assert ours("$-", env, False) == ["ok", "$-"]


@pytest.mark.skipif(not oracle.wsl_available(), reason="WSL with dash is not available")
def test_live_dash_agrees_on_a_fresh_seeded_batch() -> None:
    rng = random.Random(4242)
    env = build_corpus.ENV
    cases = [(build_corpus.generate(rng), env, rng.random() < 0.2) for _ in range(400)]
    results = oracle.run_shell("dash", cases)
    mismatches = [
        (template, strict, ours(template, env, strict), list(result))
        for (template, _, strict), result in zip(cases, results, strict=True)
        if ours(template, env, strict) != list(result) and template not in DEVIATIONS
    ]
    assert mismatches == []
