"""Build tests/data/oracle_corpus.json: templates expanded by dash and bash --posix.

The templates are generated by hand-written rules from a fixed seed (they are
not copied from any external source); the expected outputs are whatever the
real shells print when each template is the body of an unquoted here-document.
Run from the repository root with WSL available:

    python scripts/build_corpus.py
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from corpus_cases import HANDWRITTEN
from oracle import run_shell, wsl_available

SEED = 20261012
COUNT = 1500
ENV = {
    "A": "abc",
    "B": "a*b.c.tar",
    "C": "/usr/local/bin",
    "D": "x y  z",
    "E": "",
    "F": "a.b.c",
    "P": "*.",
    "Q": "\\*",
    "R": "[ab]",
}
NAMES = [*ENV, "U", "V"]
LITERALS = ["a", "b", ".", "/", "-", "_", " ", ":", "x", "{", "}", "'", '"', "\\$", "\\\\", "\\a"]
PATTERN_BITS = ["*", "?", ".", "a", "b", "c", "/", "[a-c]", "[!.]", "[[:alpha:]]", "\\*", "'*'"]
PATTERN_BITS += ['"*"', "[]a]", "[.]", "t*", "*/"]
OPS = ["", ":-", "-", ":=", "=", ":+", "+", ":?", "?", "#", "##", "%", "%%", "len"]


def _word(rng: random.Random, depth: int, pattern: bool) -> str:
    parts: list[str] = []
    for _ in range(rng.randint(0, 3)):
        roll = rng.random()
        if roll < 0.25 and depth < 3:
            parts.append(_reference(rng, depth + 1))
        elif pattern:
            parts.append(rng.choice(PATTERN_BITS))
        elif roll < 0.35:
            parts.append('"' + rng.choice(["a}b", "x", "$A", "\\}"]) + '"')
        else:
            literal = rng.choice(LITERALS)
            parts.append({"}": "\\}", '"': "x"}.get(literal, literal))
    word = "".join(parts)
    return word[:-1] + "x" if word.endswith("\\") else word


def _reference(rng: random.Random, depth: int) -> str:
    name = rng.choice(NAMES)
    op = rng.choice(OPS)
    if op == "" and rng.random() < 0.5:
        return "$" + name
    if op == "":
        return "${" + name + "}"
    if op == "len":
        return "${#" + name + "}"
    pattern = op[0] in "#%"
    word = _word(rng, depth, pattern)
    if pattern and word.startswith(op[0]):
        word = "x" + word
    return "${" + name + op + word + "}"


def generate(rng: random.Random) -> str:
    parts: list[str] = []
    for _ in range(rng.randint(1, 4)):
        if rng.random() < 0.6:
            parts.append(_reference(rng, 0))
        else:
            parts.append(rng.choice(LITERALS))
    text = "".join(parts)
    return text + "." if text.endswith("\\") else text


def main() -> int:
    if not wsl_available():
        print("WSL with dash is not available; the corpus was not rebuilt.", file=sys.stderr)
        return 1
    rng = random.Random(SEED)
    cases = [(t, ENV, strict) for t, strict in HANDWRITTEN]
    cases += [(generate(rng), ENV, rng.random() < 0.2) for _ in range(COUNT)]
    dash = run_shell("dash", cases)
    bash = run_shell("bash", cases)
    rows = [
        {"template": t, "strict": s, "dash": list(d), "bash": list(b)}
        for (t, _, s), d, b in zip(cases, dash, bash, strict=True)
    ]
    document = {
        "about": "Templates generated by scripts/build_corpus.py (hand-written rules, seed "
        f"{SEED}); outputs printed by dash and bash --posix in WSL as here-document bodies.",
        "env": ENV,
        "cases": rows,
    }
    target = Path(__file__).parent.parent / "tests" / "data" / "oracle_corpus.json"
    target.parent.mkdir(exist_ok=True)
    target.write_text(json.dumps(document, indent=1, ensure_ascii=False) + "\n", "utf-8")
    agreed = sum(1 for row in rows if row["dash"] == row["bash"])
    print(f"wrote {len(rows)} cases; dash and bash agree on {agreed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
